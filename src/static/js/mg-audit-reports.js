function renderAuditReports() {
    var content = document.getElementById('mg-content');
    content.innerHTML = '<div style="padding:var(--space-inset);text-align:center;color:var(--muted);">Loading...</div>';

    var baseUrl = getBaseUrl();

    // Load both the artefact list and the test report summary in parallel
    Promise.all([
        fetch(baseUrl + '/api/v1/governance/audit-reports', {mode: 'cors'}).then(function(r) { return r.json(); }),
        fetch(baseUrl + '/api/v1/governance/test-report/summary', {mode: 'cors'}).then(function(r) { return r.json(); }).catch(function() { return null; })
    ]).then(function(results) {
        var artefactData = results[0];
        var testData     = results[1];
        _renderAuditReportsContent(artefactData, testData, baseUrl);
    }).catch(function(err) {
        content.innerHTML = '<div style="padding:var(--space-inset);text-align:center;color:var(--red);">Failed to load audit reports</div>';
        console.error('Audit reports error:', err);
    });
}

function _renderAuditReportsContent(artefactData, testData, baseUrl) {
    var content = document.getElementById('mg-content');
    var reports = (artefactData && artefactData.reports) || [];
    var coverageAvailable = (artefactData && artefactData.coverage_available) || false;

    var html = '<div style="padding:var(--space-8);">';

    // ── Test Suite Status panel ──────────────────────────────────
    html += _renderTestSuitePanel(testData, baseUrl);

    // ── Artefact file cards ──────────────────────────────────────
    html += '<div style="font-size:var(--size-md);font-weight:700;color:var(--text);margin:var(--space-wide) 0 var(--space-4);">Audit Evidence Package</div>';
    html += '<div style="font-size:var(--size-xs);color:var(--muted);margin-bottom:var(--space-5);">Generated by <code>python phys.py test --audit</code></div>';

    if (reports.length === 0 && !coverageAvailable) {
        html += '<div style="padding:var(--space-10);text-align:center;border:2px dashed var(--line);border-radius:var(--radius-lg);color:var(--muted);">';
        html += '<div style="font-size:var(--size-xs);margin-bottom:var(--space-4);">No artefact files found.</div>';
        html += '<code style="font-size:var(--size-sm);background:var(--sunken);padding:var(--space-2) var(--space-6);border-radius:var(--radius-4);border:1px solid var(--line);">python phys.py test --audit --pdf</code>';
        html += '</div>';
    } else {
        html += '<div style="background:var(--ok-bg);border:1px solid var(--ok-line);border-radius:var(--radius-md);padding:var(--space-4) var(--space-7);margin-bottom:var(--space-6);font-size:var(--size-xs);color:var(--green-dark);">';
        html += '<b>SR 11-7 / SS1/23 Evidence</b> &mdash; Retain for regulatory inspection and MRC reporting.';
        html += '</div>';

        html += '<div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(240px,1fr));gap:var(--space-5);margin-bottom:var(--space-8);">';
        if (coverageAvailable) {
            html += _auditCard('coverage/index.html', 'Coverage HTML', 'HTML', null, null,
                baseUrl + '/api/v1/governance/audit-reports/coverage', 'Open', 'var(--info)');
        }
        reports.forEach(function(r) {
            var actionUrl = baseUrl + '/api/v1/governance/audit-reports/file/' + encodeURIComponent(r.filename);
            var actionLabel = r.type === 'PDF' ? 'View' : 'Download';
            var actionColour = r.type === 'PDF' ? 'var(--accent)' : 'var(--text-2)';
            html += _auditCard(r.filename, r.filename, r.type, r.size, r.modified,
                               actionUrl, actionLabel, actionColour);
        });
        html += '</div>';
    }

    html += '</div>';
    content.innerHTML = html;

    // Stats bar
    var total = reports.length + (coverageAvailable ? 1 : 0);
    var statsHtml = '<span>Artefacts: <b>' + total + '</b></span>';
    if (testData && testData.summary) {
        var s = testData.summary;
        var failColour = s.failed > 0 ? 'var(--red-dark)' : 'var(--green-dark)';
        statsHtml += ' &mdash; Tests: <b>' + s.total + '</b> &nbsp; '
            + '<span style="color:' + failColour + ';font-weight:700;">' + s.failed + ' failed</span>'
            + ' &nbsp; <span style="color:var(--green-dark);">' + s.passed + ' passed</span>';
    }
    document.getElementById('mg-stats-bar').innerHTML = statsHtml;
}

// ── Test suite status panel ──────────────────────────────────────
function _renderTestSuitePanel(testData, baseUrl) {
    var notFound  = !testData || testData.status === 'not_found';
    var isRunning = testData && testData.running;
    var failures  = (testData && testData.failures) || [];
    var summary   = (testData && testData.summary) || {};
    var genAt     = (testData && testData.generated_at) ? testData.generated_at.slice(0,19).replace('T',' ') : '';

    var panelColour = notFound ? 'var(--warn-bg-warm)' : (failures.length > 0 ? 'var(--danger-bg-soft)' : 'var(--ok-bg)');
    var borderColour = notFound ? 'var(--warn-line-pale)' : (failures.length > 0 ? 'var(--danger-line-alt)' : 'var(--ok-line)');

    var html = '<div style="border:1px solid ' + borderColour + ';border-radius:var(--radius-lg);background:' + panelColour + ';padding:var(--space-7);margin-bottom:var(--space-8);">';

    // Header row
    html += '<div style="display:flex;justify-content:space-between;align-items:center;margin-bottom:var(--space-5);">';
    html += '<div>';
    html += '<div style="font-size:var(--size-md);font-weight:700;color:var(--text);">Test Suite Status</div>';
    if (genAt) {
        html += '<div style="font-size:var(--size-xxs);color:var(--muted);margin-top:var(--space-1);">Last run: ' + genAt + '</div>';
    }
    html += '</div>';
    html += '<div style="display:flex;gap:var(--space-4);align-items:center;">';
    if (isRunning) {
        html += '<span style="font-size:var(--size-xs);color:var(--text-2);padding:var(--space-2) var(--space-5);background:var(--warn-bg-warm);border:1px solid var(--warn-line-pale);border-radius:var(--radius-4);">&#9203; Running...</span>';
    }
    html += '<button onclick="_runTestSuite()" style="padding:var(--space-3) var(--space-6);font-size:var(--size-xs);font-weight:600;border:1px solid var(--accent);border-radius:var(--radius-4);background:var(--accent-soft);color:var(--accent);cursor:pointer;">'
          + (isRunning ? '&#8635; Re-run' : '&#9654; Run Tests') + '</button>';
    html += '</div>';
    html += '</div>';

    if (notFound) {
        html += '<div style="font-size:var(--size-xs);color:var(--muted);">No test report yet. Click <b>&#9654; Run Tests</b> to generate one (takes ~2 min).</div>';
    } else {
        // Summary bar
        var fc = failures.length > 0 ? 'var(--red-dark)' : 'var(--green-dark)';
        html += '<div style="display:flex;gap:var(--space-8);margin-bottom:var(--space-5);font-size:var(--size-sm);">';
        html += '<span>Total: <b>' + (summary.total || 0) + '</b></span>';
        html += '<span style="color:var(--green-dark);">&#10003; Passed: <b>' + (summary.passed || 0) + '</b></span>';
        html += '<span style="color:' + fc + ';">&#10007; Failed: <b>' + (summary.failed || 0) + '</b></span>';
        html += '<span style="color:var(--muted);">&#8212; Skipped: <b>' + (summary.skipped || 0) + '</b></span>';
        html += '</div>';

        if (failures.length === 0) {
            html += '<div style="font-size:var(--size-sm);color:var(--green-dark);font-weight:600;">&#10003; All tests passing.</div>';
        } else {
            // Failure table
            html += '<div style="font-size:var(--size-xs);font-weight:600;color:var(--red-dark);margin-bottom:var(--space-3);">' + failures.length + ' test' + (failures.length > 1 ? 's' : '') + ' failing:</div>';
            html += '<table style="width:100%;border-collapse:collapse;font-size:var(--size-xs);background:var(--panel);border-radius:var(--radius-md);overflow:hidden;">';
            html += '<thead><tr style="background:var(--danger-line-alt);color:var(--red-deep);">';
            html += '<th style="padding:var(--space-3) var(--space-5);text-align:left;font-weight:600;">#</th>';
            html += '<th style="padding:var(--space-3) var(--space-5);text-align:left;font-weight:600;">Test</th>';
            html += '<th style="padding:var(--space-3) var(--space-5);text-align:left;font-weight:600;">File</th>';
            html += '<th style="padding:var(--space-3) var(--space-5);text-align:left;font-weight:600;">Error (truncated)</th>';
            html += '</tr></thead><tbody>';

            failures.forEach(function(f, idx) {
                var rowBg = idx % 2 === 0 ? 'var(--panel)' : 'var(--raised)';
                var shortName = (f['class'] ? f['class'] + '::' : '') + f.name;
                var shortFile = f.file.replace('tests/', '');
                var errLine = (f.longrepr || '').split('\n').filter(function(l) {
                    return l.trim().startsWith('AssertionError') || l.trim().startsWith('E ') || l.trim().startsWith('assert');
                })[0] || (f.longrepr || '').split('\n').slice(-2).join(' ');
                errLine = errLine.replace(/^E\s+/, '').trim();
                if (errLine.length > 90) errLine = errLine.slice(0, 90) + '…';
                var safeId = 'tr_detail_' + idx;

                html += '<tr style="background:' + rowBg + ';border-top:1px solid var(--danger-line-alt);cursor:pointer;" onclick="_toggleFailureDetail(&quot;' + safeId + '&quot;)">';
                html += '<td style="padding:var(--space-3) var(--space-5);color:var(--red-deep);font-weight:700;">' + (idx + 1) + '</td>';
                html += '<td style="padding:var(--space-3) var(--space-5);font-family:monospace;word-break:break-all;">' + shortName + '</td>';
                html += '<td style="padding:var(--space-3) var(--space-5);color:var(--muted);">' + shortFile + '</td>';
                html += '<td style="padding:var(--space-3) var(--space-5);color:var(--text-2);font-family:monospace;">' + (errLine || '—') + '</td>';
                html += '</tr>';
                // Detail row (collapsed by default)
                var escapedRepr = (f.longrepr || '').replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
                html += '<tr id="' + safeId + '" style="display:none;background:var(--danger-bg-pale);">';
                html += '<td colspan="4" style="padding:var(--space-4) var(--space-8);">';
                html += '<pre style="font-size:var(--size-xxs);color:var(--text);background:var(--panel);border:1px solid var(--danger-line-alt);border-radius:var(--radius-4);padding:var(--space-4);overflow:auto;max-height:200px;white-space:pre-wrap;">' + escapedRepr + '</pre>';
                html += '</td></tr>';
            });

            html += '</tbody></table>';
            html += '<div style="font-size:var(--size-xxs);color:var(--muted);margin-top:var(--space-3);">Click a row to expand/collapse full traceback.</div>';
        }
    }

    html += '</div>';
    return html;
}

function _toggleFailureDetail(rowId) {
    var row = document.getElementById(rowId);
    if (row) {
        row.style.display = row.style.display === 'none' ? 'table-row' : 'none';
    }
}

function _runTestSuite() {
    var baseUrl = getBaseUrl();
    fetch(baseUrl + '/api/v1/governance/test-report/run', {method: 'POST', mode: 'cors'})
        .then(function(r) { return r.json(); })
        .then(function(data) {
            if (data.status === 'started') {
                _openTerminalPopup(baseUrl);
            } else if (data.status === 'running') {
                _openTerminalPopup(baseUrl);  // show existing run
            } else {
                alert(data.message || 'Unknown response.');
            }
        })
        .catch(function(err) { alert('Error starting test run: ' + err); });
}

function _openTerminalPopup(baseUrl) {
    // Remove any existing popup
    var existing = document.getElementById('_audit-terminal-overlay');
    if (existing) existing.remove();

    var overlay = document.createElement('div');
    overlay.id = '_audit-terminal-overlay';
    overlay.style.cssText = 'position:fixed;top:0;left:0;width:100%;height:100%;background:var(--scrim);z-index:9000;display:flex;align-items:center;justify-content:center;';

    overlay.innerHTML =
        '<div style="background:var(--log-bg);border-radius:var(--radius-lg);width:760px;max-width:95vw;height:520px;display:flex;flex-direction:column;box-shadow:var(--shadow-modal);">' +
            '<div style="display:flex;justify-content:space-between;align-items:center;padding:var(--space-5) var(--space-8);background:var(--log-header);border-radius:var(--radius-lg) var(--radius-lg) 0 0;border-bottom:1px solid var(--rv-ink-2);">' +
                '<div style="display:flex;align-items:center;gap:var(--space-4);">' +
                    '<span style="width:12px;height:12px;background:var(--log-close);border-radius:50%;display:inline-block;"></span>' +
                    '<span style="width:12px;height:12px;background:var(--log-minimise);border-radius:50%;display:inline-block;"></span>' +
                    '<span style="width:12px;height:12px;background:var(--log-expand);border-radius:50%;display:inline-block;"></span>' +
                    '<span style="font-size:var(--size-sm);color:var(--disabled);margin-left:var(--space-4);font-family:monospace;">python phys.py test --audit --pdf</span>' +
                '</div>' +
                '<div style="display:flex;gap:var(--space-4);align-items:center;">' +
                    '<span id="_audit-terminal-status" style="font-size:var(--size-xs);color:var(--log-minimise);font-family:monospace;">&#9679; Running...</span>' +
                    '<button onclick="document.getElementById(\'_audit-terminal-overlay\').remove()" ' +
                        'style="border:none;background:var(--text-2);color:var(--panel);border-radius:var(--radius-4);padding:var(--space-2) var(--space-5);cursor:pointer;font-size:var(--size-sm);">&#10005; Close</button>' +
                '</div>' +
            '</div>' +
            '<div id="_audit-terminal-body" style="flex:1;overflow-y:auto;padding:var(--space-6) var(--space-8);font-family:monospace;font-size:var(--size-xs);line-height:1.6;color:var(--log-text);white-space:pre-wrap;word-break:break-word;">' +
                '<span style="color:var(--muted);">Connecting...</span>' +
            '</div>' +
            '<div style="padding:var(--space-4) var(--space-8);background:var(--log-header);border-top:1px solid var(--rv-ink-2);border-radius:0 0 var(--radius-lg) var(--radius-lg);display:flex;justify-content:space-between;align-items:center;">' +
                '<span style="font-size:var(--size-xxs);color:var(--text-3);font-family:monospace;">This typically takes 3–5 minutes</span>' +
                '<button id="_audit-terminal-refresh-btn" onclick="_auditTerminalRefreshNow()" ' +
                    'style="display:none;padding:var(--space-2) var(--space-7);font-size:var(--size-xs);font-weight:600;border:1px solid var(--log-expand);border-radius:var(--radius-4);background:var(--log-ok-bg);color:var(--log-expand);cursor:pointer;">&#8635; Refresh Audit Tab</button>' +
            '</div>' +
        '</div>';

    document.body.appendChild(overlay);

    // Poll output every 2 seconds
    var pollInterval = setInterval(function() {
        fetch(baseUrl + '/api/v1/governance/test-report/output', {mode: 'cors'})
            .then(function(r) { return r.json(); })
            .then(function(data) {
                var body = document.getElementById('_audit-terminal-body');
                var status = document.getElementById('_audit-terminal-status');
                var refreshBtn = document.getElementById('_audit-terminal-refresh-btn');
                if (!body) { clearInterval(pollInterval); return; }

                // Render lines with colour hints
                var html = data.lines.map(function(line) {
                    if (!line) return '<br>';
                    var col = 'var(--log-text)';
                    if (line.indexOf('PASSED') >= 0 || line.indexOf('passed') >= 0 || line.indexOf('complete') >= 0) col = 'var(--log-expand)';
                    else if (line.indexOf('FAILED') >= 0 || line.indexOf('failed') >= 0 || line.indexOf('ERROR') >= 0) col = 'var(--log-close)';
                    else if (line.indexOf('===') >= 0 || line.indexOf('Step') >= 0) col = 'var(--log-minimise)';
                    else if (line.indexOf('warnings') >= 0 || line.indexOf('WARN') >= 0) col = 'var(--log-warn)';
                    else if (line.charAt(0) === ' ') col = 'var(--log-info)';
                    var safe = line.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
                    return '<span style="color:' + col + ';">' + safe + '</span>';
                }).join('\n');
                body.innerHTML = html || '<span style="color:var(--muted);">Waiting for output...</span>';
                // Auto-scroll to bottom
                body.scrollTop = body.scrollHeight;

                if (!data.running) {
                    clearInterval(pollInterval);
                    if (status) {
                        status.style.color = Theme.value('log-expand');
                        status.innerHTML = '&#10003; Done';
                    }
                    if (refreshBtn) refreshBtn.style.display = 'inline-block';
                }
            })
            .catch(function() { /* server not ready yet */ });
    }, 2000);
}

function _auditTerminalRefreshNow() {
    var overlay = document.getElementById('_audit-terminal-overlay');
    if (overlay) overlay.remove();
    renderAuditReports();
}

// Expose functions called from onclick attributes (which execute in global scope,
// not inside this IIFE).
window._runTestSuite        = _runTestSuite;
window._toggleFailureDetail = _toggleFailureDetail;
window._auditTerminalRefreshNow = _auditTerminalRefreshNow;

function _auditCard(key, label, typeBadge, size, modified, actionUrl, actionLabel, actionColour) {
    var iconMap = {PDF: '&#128196;', XML: '&#128209;', HTML: '&#127760;', JSON: '&#128202;', LaTeX: '&#128195;', Log: '&#128203;'};
    var icon = iconMap[typeBadge] || '&#128196;';
    var badgeColour = Theme.ramp('report_format')[typeBadge] || Theme.value('text-2');

    var sizeStr = '';
    if (size !== null && size !== undefined) {
        sizeStr = size >= 1048576 ? (size / 1048576).toFixed(1) + ' MB' : (size / 1024).toFixed(1) + ' KB';
    }
    var modStr = modified ? modified.slice(0, 16).replace('T', ' ') : '';

    var html = '<div style="border:1px solid var(--line);border-radius:var(--radius-lg);padding:var(--space-7);background:var(--panel);display:flex;flex-direction:column;gap:var(--space-4);">';
    html += '<div style="display:flex;align-items:center;gap:var(--space-5);">';
    html += '<span style="font-size:var(--size-28);line-height:1;">' + icon + '</span>';
    html += '<div style="flex:1;min-width:0;">';
    html += '<div style="font-size:var(--size-sm);font-weight:600;color:var(--text);word-break:break-word;">' + label + '</div>';
    html += '<div style="margin-top:var(--space-2);">';
    html += '<span style="font-size:var(--size-xxs);font-weight:600;color:var(--inverse);background:' + badgeColour + ';padding:var(--space-hair) var(--space-3);border-radius:var(--radius-sm);">' + typeBadge + '</span>';
    if (sizeStr) html += '<span style="font-size:var(--size-xxs);color:var(--muted);margin-left:var(--space-3);">' + sizeStr + '</span>';
    html += '</div>';
    html += '</div>';
    html += '</div>';
    if (modStr) {
        html += '<div style="font-size:var(--size-xxs);color:var(--disabled);">Modified: ' + modStr + '</div>';
    }
    html += '<a href="' + actionUrl + '" target="_blank" style="display:block;text-align:center;padding:var(--space-3);font-size:var(--size-xs);font-weight:600;color:' + actionColour + ';border:1px solid ' + actionColour + ';border-radius:var(--radius-4);text-decoration:none;margin-top:auto;">' + actionLabel + ' &rarr;</a>';
    html += '</div>';
    return html;
}
