function renderAuditReports() {
    var content = document.getElementById('mg-content');
    content.innerHTML = '<div style="padding:40px;text-align:center;color:#888;">Loading...</div>';

    var baseUrl = getBaseUrl();

    // Load both the artefact list and the test report summary in parallel
    Promise.all([
        fetch(baseUrl + '/api/v1/governance/audit-reports', {mode: 'cors'}).then(function(r) { return r.json(); }),
        fetch(baseUrl + '/api/v1/governance/test-report/summary', {mode: 'cors'}).then(function(r) { return r.json(); }).catch(function() { return null; })
    ]).then(function(results) {
        var artefactData = results[0];
        var testData     = results[1];
        _renderAuditReportsContent(artefactData, testData, baseUrl);
    }).catch(function(err) {
        content.innerHTML = '<div style="padding:40px;text-align:center;color:red;">Failed to load audit reports</div>';
        console.error('Audit reports error:', err);
    });
}

function _renderAuditReportsContent(artefactData, testData, baseUrl) {
    var content = document.getElementById('mg-content');
    var reports = (artefactData && artefactData.reports) || [];
    var coverageAvailable = (artefactData && artefactData.coverage_available) || false;

    var html = '<div style="padding:16px;">';

    // ── Test Suite Status panel ──────────────────────────────────
    html += _renderTestSuitePanel(testData, baseUrl);

    // ── Artefact file cards ──────────────────────────────────────
    html += '<div style="font-size:13px;font-weight:700;color:#333;margin:20px 0 8px;">Audit Evidence Package</div>';
    html += '<div style="font-size:11px;color:#888;margin-bottom:10px;">Generated by <code>python phys.py test --audit</code></div>';

    if (reports.length === 0 && !coverageAvailable) {
        html += '<div style="padding:24px;text-align:center;border:2px dashed #e0e0e0;border-radius:8px;color:#888;">';
        html += '<div style="font-size:11px;margin-bottom:8px;">No artefact files found.</div>';
        html += '<code style="font-size:12px;background:#f5f5f5;padding:4px 12px;border-radius:4px;border:1px solid #e0e0e0;">python phys.py test --audit --pdf</code>';
        html += '</div>';
    } else {
        html += '<div style="background:#e8f5e9;border:1px solid #c8e6c9;border-radius:6px;padding:8px 14px;margin-bottom:12px;font-size:11px;color:#2e7d32;">';
        html += '<b>SR 11-7 / SS1/23 Evidence</b> &mdash; Retain for regulatory inspection and MRC reporting.';
        html += '</div>';

        html += '<div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(240px,1fr));gap:10px;margin-bottom:16px;">';
        if (coverageAvailable) {
            html += _auditCard('coverage/index.html', 'Coverage HTML', 'HTML', null, null,
                baseUrl + '/api/v1/governance/audit-reports/coverage', 'Open', '#0288d1');
        }
        reports.forEach(function(r) {
            var actionUrl = baseUrl + '/api/v1/governance/audit-reports/file/' + encodeURIComponent(r.filename);
            var actionLabel = r.type === 'PDF' ? 'View' : 'Download';
            var actionColour = r.type === 'PDF' ? '#1976d2' : '#555';
            html += _auditCard(r.filename, r.filename, r.type, r.size, r.modified,
                               actionUrl, actionLabel, actionColour);
        });
        html += '</div>';
    }

    html += '</div>';
    content.innerHTML = html;

    // Stats bar
    var total = reports.length + (coverageAvailable ? 1 : 0);
    var statsHtml = '<span>Artefacts: <b>' + total + '</b></span>';
    if (testData && testData.summary) {
        var s = testData.summary;
        var failColour = s.failed > 0 ? '#c62828' : '#2e7d32';
        statsHtml += ' &mdash; Tests: <b>' + s.total + '</b> &nbsp; '
            + '<span style="color:' + failColour + ';font-weight:700;">' + s.failed + ' failed</span>'
            + ' &nbsp; <span style="color:#2e7d32;">' + s.passed + ' passed</span>';
    }
    document.getElementById('mg-stats-bar').innerHTML = statsHtml;
}

// ── Test suite status panel ──────────────────────────────────────
function _renderTestSuitePanel(testData, baseUrl) {
    var notFound  = !testData || testData.status === 'not_found';
    var isRunning = testData && testData.running;
    var failures  = (testData && testData.failures) || [];
    var summary   = (testData && testData.summary) || {};
    var genAt     = (testData && testData.generated_at) ? testData.generated_at.slice(0,19).replace('T',' ') : '';

    var panelColour = notFound ? '#fff3e0' : (failures.length > 0 ? '#ffebee' : '#e8f5e9');
    var borderColour = notFound ? '#ffe0b2' : (failures.length > 0 ? '#ffcdd2' : '#c8e6c9');

    var html = '<div style="border:1px solid ' + borderColour + ';border-radius:8px;background:' + panelColour + ';padding:14px;margin-bottom:16px;">';

    // Header row
    html += '<div style="display:flex;justify-content:space-between;align-items:center;margin-bottom:10px;">';
    html += '<div>';
    html += '<div style="font-size:13px;font-weight:700;color:#333;">Test Suite Status</div>';
    if (genAt) {
        html += '<div style="font-size:10px;color:#888;margin-top:2px;">Last run: ' + genAt + '</div>';
    }
    html += '</div>';
    html += '<div style="display:flex;gap:8px;align-items:center;">';
    if (isRunning) {
        html += '<span style="font-size:11px;color:#555;padding:4px 10px;background:#fff3e0;border:1px solid #ffe0b2;border-radius:4px;">&#9203; Running...</span>';
    }
    html += '<button onclick="_runTestSuite()" style="padding:5px 12px;font-size:11px;font-weight:600;border:1px solid #1976d2;border-radius:4px;background:#e3f2fd;color:#1976d2;cursor:pointer;">'
          + (isRunning ? '&#8635; Re-run' : '&#9654; Run Tests') + '</button>';
    html += '</div>';
    html += '</div>';

    if (notFound) {
        html += '<div style="font-size:11px;color:#888;">No test report yet. Click <b>&#9654; Run Tests</b> to generate one (takes ~2 min).</div>';
    } else {
        // Summary bar
        var fc = failures.length > 0 ? '#c62828' : '#2e7d32';
        html += '<div style="display:flex;gap:16px;margin-bottom:10px;font-size:12px;">';
        html += '<span>Total: <b>' + (summary.total || 0) + '</b></span>';
        html += '<span style="color:#2e7d32;">&#10003; Passed: <b>' + (summary.passed || 0) + '</b></span>';
        html += '<span style="color:' + fc + ';">&#10007; Failed: <b>' + (summary.failed || 0) + '</b></span>';
        html += '<span style="color:#888;">&#8212; Skipped: <b>' + (summary.skipped || 0) + '</b></span>';
        html += '</div>';

        if (failures.length === 0) {
            html += '<div style="font-size:12px;color:#2e7d32;font-weight:600;">&#10003; All tests passing.</div>';
        } else {
            // Failure table
            html += '<div style="font-size:11px;font-weight:600;color:#c62828;margin-bottom:6px;">' + failures.length + ' test' + (failures.length > 1 ? 's' : '') + ' failing:</div>';
            html += '<table style="width:100%;border-collapse:collapse;font-size:11px;background:white;border-radius:6px;overflow:hidden;">';
            html += '<thead><tr style="background:#ffcdd2;color:#b71c1c;">';
            html += '<th style="padding:6px 10px;text-align:left;font-weight:600;">#</th>';
            html += '<th style="padding:6px 10px;text-align:left;font-weight:600;">Test</th>';
            html += '<th style="padding:6px 10px;text-align:left;font-weight:600;">File</th>';
            html += '<th style="padding:6px 10px;text-align:left;font-weight:600;">Error (truncated)</th>';
            html += '</tr></thead><tbody>';

            failures.forEach(function(f, idx) {
                var rowBg = idx % 2 === 0 ? '#fff' : '#fafafa';
                var shortName = (f['class'] ? f['class'] + '::' : '') + f.name;
                var shortFile = f.file.replace('tests/', '');
                var errLine = (f.longrepr || '').split('\n').filter(function(l) {
                    return l.trim().startsWith('AssertionError') || l.trim().startsWith('E ') || l.trim().startsWith('assert');
                })[0] || (f.longrepr || '').split('\n').slice(-2).join(' ');
                errLine = errLine.replace(/^E\s+/, '').trim();
                if (errLine.length > 90) errLine = errLine.slice(0, 90) + '…';
                var safeId = 'tr_detail_' + idx;

                html += '<tr style="background:' + rowBg + ';border-top:1px solid #ffcdd2;cursor:pointer;" onclick="_toggleFailureDetail(&quot;' + safeId + '&quot;)">';
                html += '<td style="padding:6px 10px;color:#b71c1c;font-weight:700;">' + (idx + 1) + '</td>';
                html += '<td style="padding:6px 10px;font-family:monospace;word-break:break-all;">' + shortName + '</td>';
                html += '<td style="padding:6px 10px;color:#888;">' + shortFile + '</td>';
                html += '<td style="padding:6px 10px;color:#555;font-family:monospace;">' + (errLine || '—') + '</td>';
                html += '</tr>';
                // Detail row (collapsed by default)
                var escapedRepr = (f.longrepr || '').replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
                html += '<tr id="' + safeId + '" style="display:none;background:#fff8f8;">';
                html += '<td colspan="4" style="padding:8px 16px;">';
                html += '<pre style="font-size:10px;color:#333;background:#fff;border:1px solid #ffcdd2;border-radius:4px;padding:8px;overflow:auto;max-height:200px;white-space:pre-wrap;">' + escapedRepr + '</pre>';
                html += '</td></tr>';
            });

            html += '</tbody></table>';
            html += '<div style="font-size:10px;color:#888;margin-top:6px;">Click a row to expand/collapse full traceback.</div>';
        }
    }

    html += '</div>';
    return html;
}

function _toggleFailureDetail(rowId) {
    var row = document.getElementById(rowId);
    if (row) {
        row.style.display = row.style.display === 'none' ? 'table-row' : 'none';
    }
}

function _runTestSuite() {
    var baseUrl = getBaseUrl();
    fetch(baseUrl + '/api/v1/governance/test-report/run', {method: 'POST', mode: 'cors'})
        .then(function(r) { return r.json(); })
        .then(function(data) {
            if (data.status === 'started') {
                _openTerminalPopup(baseUrl);
            } else if (data.status === 'running') {
                _openTerminalPopup(baseUrl);  // show existing run
            } else {
                alert(data.message || 'Unknown response.');
            }
        })
        .catch(function(err) { alert('Error starting test run: ' + err); });
}

function _openTerminalPopup(baseUrl) {
    // Remove any existing popup
    var existing = document.getElementById('_audit-terminal-overlay');
    if (existing) existing.remove();

    var overlay = document.createElement('div');
    overlay.id = '_audit-terminal-overlay';
    overlay.style.cssText = 'position:fixed;top:0;left:0;width:100%;height:100%;background:rgba(0,0,0,0.6);z-index:9000;display:flex;align-items:center;justify-content:center;';

    overlay.innerHTML =
        '<div style="background:#1e1e1e;border-radius:8px;width:760px;max-width:95vw;height:520px;display:flex;flex-direction:column;box-shadow:0 8px 40px rgba(0,0,0,0.6);">' +
            '<div style="display:flex;justify-content:space-between;align-items:center;padding:10px 16px;background:#2d2d2d;border-radius:8px 8px 0 0;border-bottom:1px solid #444;">' +
                '<div style="display:flex;align-items:center;gap:8px;">' +
                    '<span style="width:12px;height:12px;background:#ff5f56;border-radius:50%;display:inline-block;"></span>' +
                    '<span style="width:12px;height:12px;background:#ffbd2e;border-radius:50%;display:inline-block;"></span>' +
                    '<span style="width:12px;height:12px;background:#27c93f;border-radius:50%;display:inline-block;"></span>' +
                    '<span style="font-size:12px;color:#aaa;margin-left:8px;font-family:monospace;">python phys.py test --audit --pdf</span>' +
                '</div>' +
                '<div style="display:flex;gap:8px;align-items:center;">' +
                    '<span id="_audit-terminal-status" style="font-size:11px;color:#ffbd2e;font-family:monospace;">&#9679; Running...</span>' +
                    '<button onclick="document.getElementById(\'_audit-terminal-overlay\').remove()" ' +
                        'style="border:none;background:#555;color:#fff;border-radius:4px;padding:3px 10px;cursor:pointer;font-size:12px;">&#10005; Close</button>' +
                '</div>' +
            '</div>' +
            '<div id="_audit-terminal-body" style="flex:1;overflow-y:auto;padding:12px 16px;font-family:monospace;font-size:11px;line-height:1.6;color:#d4d4d4;white-space:pre-wrap;word-break:break-word;">' +
                '<span style="color:#888;">Connecting...</span>' +
            '</div>' +
            '<div style="padding:8px 16px;background:#2d2d2d;border-top:1px solid #444;border-radius:0 0 8px 8px;display:flex;justify-content:space-between;align-items:center;">' +
                '<span style="font-size:10px;color:#666;font-family:monospace;">This typically takes 3–5 minutes</span>' +
                '<button id="_audit-terminal-refresh-btn" onclick="_auditTerminalRefreshNow()" ' +
                    'style="display:none;padding:4px 14px;font-size:11px;font-weight:600;border:1px solid #27c93f;border-radius:4px;background:#1a3a1a;color:#27c93f;cursor:pointer;">&#8635; Refresh Audit Tab</button>' +
            '</div>' +
        '</div>';

    document.body.appendChild(overlay);

    // Poll output every 2 seconds
    var pollInterval = setInterval(function() {
        fetch(baseUrl + '/api/v1/governance/test-report/output', {mode: 'cors'})
            .then(function(r) { return r.json(); })
            .then(function(data) {
                var body = document.getElementById('_audit-terminal-body');
                var status = document.getElementById('_audit-terminal-status');
                var refreshBtn = document.getElementById('_audit-terminal-refresh-btn');
                if (!body) { clearInterval(pollInterval); return; }

                // Render lines with colour hints
                var html = data.lines.map(function(line) {
                    if (!line) return '<br>';
                    var col = '#d4d4d4';
                    if (line.indexOf('PASSED') >= 0 || line.indexOf('passed') >= 0 || line.indexOf('complete') >= 0) col = '#27c93f';
                    else if (line.indexOf('FAILED') >= 0 || line.indexOf('failed') >= 0 || line.indexOf('ERROR') >= 0) col = '#ff5f56';
                    else if (line.indexOf('===') >= 0 || line.indexOf('Step') >= 0) col = '#ffbd2e';
                    else if (line.indexOf('warnings') >= 0 || line.indexOf('WARN') >= 0) col = '#e5a00d';
                    else if (line.charAt(0) === ' ') col = '#9cdcfe';
                    var safe = line.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
                    return '<span style="color:' + col + ';">' + safe + '</span>';
                }).join('\n');
                body.innerHTML = html || '<span style="color:#888;">Waiting for output...</span>';
                // Auto-scroll to bottom
                body.scrollTop = body.scrollHeight;

                if (!data.running) {
                    clearInterval(pollInterval);
                    if (status) {
                        status.style.color = '#27c93f';
                        status.innerHTML = '&#10003; Done';
                    }
                    if (refreshBtn) refreshBtn.style.display = 'inline-block';
                }
            })
            .catch(function() { /* server not ready yet */ });
    }, 2000);
}

function _auditTerminalRefreshNow() {
    var overlay = document.getElementById('_audit-terminal-overlay');
    if (overlay) overlay.remove();
    renderAuditReports();
}

// Expose functions called from onclick attributes (which execute in global scope,
// not inside this IIFE).
window._runTestSuite        = _runTestSuite;
window._toggleFailureDetail = _toggleFailureDetail;
window._auditTerminalRefreshNow = _auditTerminalRefreshNow;

function _auditCard(key, label, typeBadge, size, modified, actionUrl, actionLabel, actionColour) {
    var iconMap = {PDF: '&#128196;', XML: '&#128209;', HTML: '&#127760;', JSON: '&#128202;', LaTeX: '&#128195;', Log: '&#128203;'};
    var icon = iconMap[typeBadge] || '&#128196;';
    var badgeColour = {PDF: '#c62828', XML: '#6a1b9a', HTML: '#0288d1', JSON: '#e65100', LaTeX: '#2e7d32', Log: '#555'}[typeBadge] || '#555';

    var sizeStr = '';
    if (size !== null && size !== undefined) {
        sizeStr = size >= 1048576 ? (size / 1048576).toFixed(1) + ' MB' : (size / 1024).toFixed(1) + ' KB';
    }
    var modStr = modified ? modified.slice(0, 16).replace('T', ' ') : '';

    var html = '<div style="border:1px solid #e0e0e0;border-radius:8px;padding:14px;background:white;display:flex;flex-direction:column;gap:8px;">';
    html += '<div style="display:flex;align-items:center;gap:10px;">';
    html += '<span style="font-size:28px;line-height:1;">' + icon + '</span>';
    html += '<div style="flex:1;min-width:0;">';
    html += '<div style="font-size:12px;font-weight:600;color:#333;word-break:break-word;">' + label + '</div>';
    html += '<div style="margin-top:3px;">';
    html += '<span style="font-size:10px;font-weight:600;color:white;background:' + badgeColour + ';padding:1px 6px;border-radius:3px;">' + typeBadge + '</span>';
    if (sizeStr) html += '<span style="font-size:10px;color:#888;margin-left:6px;">' + sizeStr + '</span>';
    html += '</div>';
    html += '</div>';
    html += '</div>';
    if (modStr) {
        html += '<div style="font-size:10px;color:#aaa;">Modified: ' + modStr + '</div>';
    }
    html += '<a href="' + actionUrl + '" target="_blank" style="display:block;text-align:center;padding:5px;font-size:11px;font-weight:600;color:' + actionColour + ';border:1px solid ' + actionColour + ';border-radius:4px;text-decoration:none;margin-top:auto;">' + actionLabel + ' &rarr;</a>';
    html += '</div>';
    return html;
}
