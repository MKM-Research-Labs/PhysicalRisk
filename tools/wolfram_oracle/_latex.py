"""LaTeX helpers every benchmark document's generated tables share.

Each model's ``latex`` module decides what its tables say; how a number, a
table or an outcome is written is decided once, here, so the documents read
alike. Generated files carry ``GENERATED`` as their first line.
"""

GENERATED = "% Generated by tools.wolfram_oracle -- do not edit.\n"


def esc(text):
    """Escape the LaTeX specials that appear in labels and paths."""
    for ch in ("&", "%", "$", "#", "_", "{", "}"):
        text = text.replace(ch, "\\" + ch)
    return text


def sci(x, digits=1):
    if x == 0:
        return "0"
    mant, exp = f"{x:.{digits}e}".split("e")
    return f"${mant}\\times10^{{{int(exp)}}}$"


def tab(caption, label, spec, header, rows):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    # adjustbox (loaded by mkm_header) shrinks a table only if it would overflow.
    return (f"\\begin{{table}}[H]\\centering\\small\n\\caption{{{caption}}}\\label{{{label}}}\n"
            f"\\begin{{adjustbox}}{{max width=\\textwidth}}\n"
            f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n"
            f"\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n\\end{{table}}\n")


def longtab(caption, label, spec, header, rows):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    return (f"{{\\footnotesize\\setlength{{\\tabcolsep}}{{4pt}}\\begin{{longtable}}{{{spec}}}\n"
            f"\\caption{{{caption}}}\\label{{{label}}}\\\\\n"
            f"\\toprule\n{header} \\\\\n\\midrule\n\\endhead\n{body}\n"
            f"\\bottomrule\n\\end{{longtable}}}}\n")


def outcome(ok):
    return "pass" if ok else "\\textbf{FAIL}"


def macros(values):
    """``\\newcommand`` lines for ``{name: value}``."""
    return GENERATED + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in values.items())


def write_files(out, prefix, files):
    """Write each ``{name: text}`` as ``<prefix><name>.tex``; return the paths."""
    paths = []
    for name, text in files.items():
        path = out / f"{prefix}{name}.tex"
        path.write_text(text)
        paths.append(path)
    return paths
