"""LaTeX for the MKM-GH-001 benchmark document, generated from a run.

The document itself (``MKM-GH-001_wolfram_benchmark.tex``) is hand-written on
the house template, ``docs/models/shared/mkm_header.tex``. Every figure it
quotes from a run comes through here — as a macro or an ``evidence_tables_*``
file it ``\\input``s — so the PDF and the CSVs always agree. Same pattern as
XV-001's ``docs/xva/_evidence_latex.py``.
"""

from datetime import date

from config.models import (
    ORACLE_FIT_LL_TOL,
    ORACLE_GEV_TABLE_PREFIX,
    ORACLE_OPERATING_MAX_T,
    ORACLE_REL_TOL,
)
from tools.wolfram_oracle.return_levels import worst

_GENERATED = "% Generated by tools.wolfram_oracle -- do not edit.\n"


def _esc(text):
    """Escape the LaTeX specials that appear in labels and paths."""
    for ch in ("&", "%", "$", "#", "_", "{", "}"):
        text = text.replace(ch, "\\" + ch)
    return text


def _sci(x):
    if x == 0:
        return "0"
    mant, exp = f"{x:.1e}".split("e")
    return f"${mant}\\times10^{{{int(exp)}}}$"


def _tab(caption, label, spec, header, rows):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    # adjustbox (loaded by mkm_header) shrinks a table only if it would overflow.
    return (f"\\begin{{table}}[H]\\centering\\small\n\\caption{{{caption}}}\\label{{{label}}}\n"
            f"\\begin{{adjustbox}}{{max width=\\textwidth}}\n"
            f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n"
            f"\\bottomrule\n\\end{{tabular}}\n\\end{{adjustbox}}\n\\end{{table}}\n")


def _longtab(caption, label, spec, header, rows):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    return (f"{{\\footnotesize\\setlength{{\\tabcolsep}}{{4pt}}\\begin{{longtable}}{{{spec}}}\n\\caption{{{caption}}}\\label{{{label}}}\\\\\n"
            f"\\toprule\n{header} \\\\\n\\midrule\n\\endhead\n{body}\n"
            f"\\bottomrule\n\\end{{longtable}}}}\n")


def _outcome(ok):
    return "pass" if ok else "\\textbf{FAIL}"


def findings(rl_rows, fit_rows, wolfram_version):
    """The checks, each as (check, result, tolerance, outcome)."""
    lv, ex = worst(rl_rows, "level_rel_err"), worst(rl_rows, "exc_rel_err")
    out = [
        (f"Return levels, $T \\le {ORACLE_OPERATING_MAX_T:,}$".replace(",", "{,}"),
         _sci(lv["level_rel_err"]), _sci(ORACLE_REL_TOL),
         _outcome(lv["level_rel_err"] <= ORACLE_REL_TOL)),
        (f"Exceedance probabilities, $T \\le {ORACLE_OPERATING_MAX_T:,}$".replace(",", "{,}"),
         _sci(ex["exc_rel_err"]), _sci(ORACLE_REL_TOL),
         _outcome(ex["exc_rel_err"] <= ORACLE_REL_TOL)),
    ]
    if wolfram_version:
        ref = max(max(r["level_wolfram_vs_ref"], r["exc_wolfram_vs_ref"]) for r in rl_rows)
        mod = max(max(r["level_model_vs_wolfram"], r["exc_model_vs_wolfram"])
                  for r in rl_rows if r["T"] <= ORACLE_OPERATING_MAX_T)
        out += [("Wolfram agrees with the reference", _sci(ref), _sci(ORACLE_REL_TOL),
                 _outcome(ref <= ORACLE_REL_TOL)),
                ("Model agrees with Wolfram", _sci(mod), _sci(ORACLE_REL_TOL),
                 _outcome(mod <= ORACLE_REL_TOL))]
    else:
        out.append(("Wolfram agrees with the reference", "not run", _sci(ORACLE_REL_TOL),
                    "\\textbf{pending}"))
    gain = max(r["ll_gain_indep"] for r in fit_rows)
    out.append(("Fit at the maximum: independent optimiser", _sci(max(gain, 0.0)),
                _sci(ORACLE_FIT_LL_TOL), _outcome(gain <= ORACLE_FIT_LL_TOL)))
    if wolfram_version:
        gain_w = max(r["ll_gain_wolfram"] for r in fit_rows)
        out.append(("Fit at the maximum: Wolfram", _sci(max(gain_w, 0.0)),
                    _sci(ORACLE_FIT_LL_TOL), _outcome(gain_w <= ORACLE_FIT_LL_TOL)))
    return out


def _ratios(fit_rows):
    rows = [r for r in fit_rows if r["truth_xi_loc_scale"] and r["family"] == "gev"]
    return [r["levels"][1000]["model"] / r["levels"][1000]["truth"] for r in rows]


def macros(prov, data_source, rl_rows, fit_rows, wolfram_version, wolfram_mode, trap):
    lv, ex = worst(rl_rows, "level_rel_err"), worst(rl_rows, "exc_rel_err")
    checks = findings(rl_rows, fit_rows, wolfram_version)
    failed = sum("FAIL" in c[3] for c in checks)
    ratios = _ratios(fit_rows)
    if wolfram_version:
        agree = max(max(r["level_wolfram_vs_ref"], r["exc_wolfram_vs_ref"]) for r in rl_rows)
        confirmed = (f"Wolfram and the 50-digit reference agree to {_sci(agree)}, so the "
                     "reference is confirmed by a second, independent implementation.")
    else:
        confirmed = ("Wolfram has not been run, so the reference rests on one "
                     "implementation until it is.")
    m = {
        "bmGenerated": date.today().isoformat(),
        "bmCodeFile": f"\\texttt{{{_esc(prov['file'])}}}",
        "bmCodeSha": f"\\texttt{{{prov['sha256'][:16]}}}",
        "bmCodeCommit": f"\\texttt{{{prov['last_commit'][:12]}}}",
        "bmCodeDirty": " (with uncommitted changes)" if prov["uncommitted_changes"] else "",
        "bmNumerics": ", ".join(f"{k} {v}" for k, v in prov["packages"].items()),
        "bmWolfram": _esc(wolfram_version) if wolfram_version else "not run",
        "bmWolframVia": f" via {wolfram_mode}" if wolfram_version else "",
        "bmWolframConfirms": confirmed,
        "bmData": _esc(data_source),
        "bmTol": _sci(ORACLE_REL_TOL),
        "bmOperatingT": f"{ORACLE_OPERATING_MAX_T:,}".replace(",", "{,}"),
        "bmWorstLevel": _sci(lv["level_rel_err"]),
        "bmWorstLevelAt": _esc(lv["id"]),
        "bmWorstExc": _sci(ex["exc_rel_err"]),
        "bmWorstExcAt": _esc(ex["id"]),
        "bmLLGain": _sci(max(max(r["ll_gain_indep"] for r in fit_rows), 0.0)),
        "bmLLTol": _sci(ORACLE_FIT_LL_TOL),
        "bmRatioMin": f"{min(ratios):.2f}" if ratios else "--",
        "bmRatioMax": f"{max(ratios):.2f}" if ratios else "--",
        "bmTrapRight": f"{trap['correct (c = -xi)']:.2f}",
        "bmTrapWrong": f"{trap['unflipped (c = +xi)']:.2f}",
        "bmChecks": f"{len(checks)}",
        "bmOutcome": ("all pass" if not failed else f"{failed} fail")
                     + ("" if wolfram_version else "; Wolfram pending"),
    }
    return _GENERATED + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items())


def _return_levels(rl_rows, wolfram_version):
    head = "Case & $T$ & Reference level & Level err & Exc.\\ err"
    spec = "lrrrr"
    if wolfram_version:
        head += " & Level vs W. & Exc.\\ vs W."
        spec += "rr"
    rows = []
    for r in rl_rows:
        row = [_esc(r["case"]), f"{r['T']:,}".replace(",", "{,}"), r["level_ref"][:16],
               _sci(r["level_rel_err"]), _sci(r["exc_rel_err"])]
        if wolfram_version:
            row += [_sci(r["level_model_vs_wolfram"]), _sci(r["exc_model_vs_wolfram"])]
        rows.append(row)
    return _longtab("GEVFitter against the 50-digit reference: relative errors. The "
                    "exceedance threshold is the exact $T$-year level, so $P(X>x_T)=1/T$",
                    "tab:bm-return-levels", spec, head, rows)


def _fit(fit_rows, wolfram_version):
    head = ("Series & Fit & $n$ & $\\hat\\xi$ model & $\\hat\\xi$ indep. & $\\xi$ true & "
            "LL gain & $x_{1000}$ model & $x_{1000}$ true")
    spec = "llrrrrrrr"
    if wolfram_version:
        head += " & $\\hat\\xi$ Wolfram & LL gain W."
        spec += "rr"
    rows = []
    for r in fit_rows:
        t, lv = r["truth_xi_loc_scale"], r["levels"][1000]
        row = [_esc(r["series"]), r["family"], str(r["n"]), f"{r['model_xi_loc_scale'][0]:.4f}",
               f"{r['indep_xi_loc_scale'][0]:.4f}", f"{t[0]:.2f}" if t else "--",
               _sci(r["ll_gain_indep"]), f"{lv['model']:.3f}",
               f"{lv['truth']:.3f}" if t else "--"]
        if wolfram_version:
            row += [f"{r['wolfram_xi_loc_scale'][0]:.4f}", _sci(r["ll_gain_wolfram"])]
        rows.append(row)
    return _tab("Maximum-likelihood fit: GEVFitter against an independent optimiser",
                "tab:bm-fit", spec, head, rows)


def write_tables(out, prov, data_source, rl_rows, fit_rows, wolfram_version, wolfram_mode, trap):
    """Write every generated .tex the document inputs; return their paths."""
    files = {
        "macros": macros(prov, data_source, rl_rows, fit_rows, wolfram_version, wolfram_mode, trap),
        "findings": _GENERATED + _tab(
            "Benchmark checks", "tab:bm-checks", "lrrl", "Check & Result & Tolerance & Outcome",
            findings(rl_rows, fit_rows, wolfram_version)),
        "return_levels": _GENERATED + _return_levels(rl_rows, wolfram_version),
        "fit": _GENERATED + _fit(fit_rows, wolfram_version),
    }
    paths = []
    for name, text in files.items():
        path = out / f"{ORACLE_GEV_TABLE_PREFIX}{name}.tex"
        path.write_text(text)
        paths.append(path)
    return paths
