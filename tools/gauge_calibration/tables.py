"""Evidence tables for the gauge-calibration document, generated from the data.

    python tools/gauge_calibration/tables.py --calibration catch/thames/gauge_calibration.json \\
        --before <input dir of the v1 run> --after <input dir of the calibrated run> \\
        --out docs/models/gauge_calibration/evidence_tables.tex

``--before``/``--after`` hold ``gaugehc.json`` (the priced yearly chances) and, for
``--after``, the storm-gauge output the weighted rises are measured from.
"""

import argparse
import json
import statistics
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]


def _tex(s):
    return str(s).replace("&", r"\&").replace("_", r"\_").replace("%", r"\%")


def _pct(x):
    return f"{100 * x:.1f}\\%"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Gauge-calibration evidence tables.")
    ap.add_argument("--calibration", type=Path, required=True)
    ap.add_argument("--before", type=Path, required=True)
    ap.add_argument("--after", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    sys.path[:0] = [str(REPO_ROOT), str(REPO_ROOT / "src")]
    from tools.gauge_calibration.build import reference_catalogue, simulated_rises

    cal = json.load(open(args.calibration))
    lam = cal["storms_per_year"]
    before = json.load(open(args.before / "gaugehc.json"))["hazard_curves"]
    after = json.load(open(args.after / "gaugehc.json"))["hazard_curves"]
    names = list(cal["gauges"])
    ids = [cal["gauges"][n]["gauge_id"] for n in names]
    catalogue = reference_catalogue(args.after, ids)
    keys = ("annual_flood_prob_alert", "annual_flood_prob_warning", "annual_flood_prob_severe")

    stations, fit, freq = [], [], []
    for n, gid in zip(names, ids):
        e = cal["gauges"][n]
        short = _tex(n.replace("Thames ", ""))
        notes = []
        if e["datum_changes"]:
            notes.append("datum change " + ", ".join(str(y) for y in e["datum_changes"]))
        if e["excluded_years"]:
            notes.append("excluded " + ", ".join(f"{x['water_year']} ({x['value_m']:.2f}\\,m)"
                                                 for x in e["excluded_years"]))
        stations.append(f"{short} & {_tex(e['ea_station'])} & {e['ea_station_km']:.2f} & "
                        f"{e['record_years']} & {'; '.join(notes) or '--'} \\\\")
        rl = simulated_rises(args.after, gid, catalogue, lam)
        o = e["fit"]["observed_rise_m"]
        fit.append(f"{short} & {e['sensitivity']:.3f} & {e['rise_exponent']:.2f} & "
                   f"{e['seasonal_offset_m']:.2f} & "
                   + " & ".join(f"{rl[T]:.2f}/{o[str(T)]:.2f}" for T in (2, 10, 20, 50)) + " \\\\")
        freq.append(f"{short} & " + " & ".join(_pct(before[gid][k]) for k in keys) + " & "
                    + " & ".join(_pct(after[gid][k]) for k in keys) + " \\\\")

    med = {k: statistics.median(after[g][k] for g in ids) for k in keys}
    prov_ids = [g for g in after if g not in ids]
    prov = {k: statistics.median(after[g][k] for g in prov_ids) for k in keys}
    d = cal["default"]
    lines = [
        "% Generated by tools/gauge_calibration/tables.py -- do not edit by hand.",
        f"\\newcommand{{\\gcBuilt}}{{{cal['built']}}}",
        f"\\newcommand{{\\gcLambda}}{{{lam}}}",
        f"\\newcommand{{\\gcNCal}}{{{len(ids)}}}",
        f"\\newcommand{{\\gcNProv}}{{{len(prov_ids)}}}",
        f"\\newcommand{{\\gcMedAlert}}{{{_pct(med[keys[0]])}}}",
        f"\\newcommand{{\\gcMedWarning}}{{{_pct(med[keys[1]])}}}",
        f"\\newcommand{{\\gcMedSevere}}{{{_pct(med[keys[2]])}}}",
        f"\\newcommand{{\\gcProvAlert}}{{{_pct(prov[keys[0]])}}}",
        f"\\newcommand{{\\gcProvWarning}}{{{_pct(prov[keys[1]])}}}",
        f"\\newcommand{{\\gcProvSevere}}{{{_pct(prov[keys[2]])}}}",
        f"\\newcommand{{\\gcDefaultS}}{{{d['sensitivity']:.3f}}}",
        f"\\newcommand{{\\gcDefaultB}}{{{d['rise_exponent']:.2f}}}",
        f"\\newcommand{{\\gcDefaultRises}}{{{d['rise_m']['alert']:.2f} / "
        f"{d['rise_m']['warning']:.2f} / {d['rise_m']['severe']:.2f}}}",
        "\\newcommand{\\gcStationRows}{%", *stations, "}",
        "\\newcommand{\\gcFitRows}{%", *fit, "}",
        "\\newcommand{\\gcFreqRows}{%", *freq, "}",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
