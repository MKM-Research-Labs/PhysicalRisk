"""Write the results: full JSON, and a LaTeX fragment the Stress Testing guide
includes in its challenger section."""

import json
from pathlib import Path

from config.models import CHALLENGER_CHAMPION

_OUTCOME_TEXT = {
    "retain": "the production GBM is \\textbf{retained}",
    "replace": "the production GBM is \\textbf{replaced} by the best challenger",
    "escalate": "the result is \\textbf{mixed} and is escalated for model-risk sign-off",
}


def _f(v, digits=4):
    return "--" if v is None else f"{v:.{digits}f}"


def _tex(s):
    return str(s).replace("_", "\\_").replace("%", "\\%")


def public(results):
    """Results without the private arrays (keys starting with '_')."""
    out = dict(results)
    out["gauges"] = [{k: v for k, v in g.items() if not k.startswith("_")}
                     for g in results["gauges"]]
    return out


def write_json(results, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(public(results), indent=1, default=float))


def write_tex(results, path: Path):
    meta, models, dec = results["meta"], results["models"], results["decision"]
    scored = [g for g in results["gauges"] if g["status"] == "scored"]
    lines = [
        "% Generated by tools/flood_classifier_challenger -- do not edit by hand.",
        *(["\\noindent\\textbf{Synthetic catalogue: a smoke run of the tool, "
           "not evidence about the production model.}", ""]
          if meta["source"] == "synthetic" else []),
        f"\\noindent\\textbf{{Run:}} {meta['date']}, source \\texttt{{{_tex(meta['source'])}}}, "
        f"{meta['n_gauges_scored']} gauges scored ({meta['n_gauges_skipped']} skipped), "
        f"{meta['n_storms']} storms per gauge, {meta['folds']} storm folds, "
        f"{meta['tune_trials']} tuning trials, {meta['seeds']} seeds, "
        f"{meta['bootstraps']} storm bootstraps.",
        "",
        "\\begin{center}\\small",
        "\\begin{tabular}{lccccccc}",
        "\\toprule",
        "\\textbf{Model} & \\textbf{Brier} & \\textbf{Log loss} & \\textbf{AUC} & "
        "\\textbf{ECE} & \\textbf{Seed s.d.} & \\textbf{Boot.\\ s.d.} & "
        "\\textbf{Mono.\\ viol.} \\\\",
        "\\midrule",
    ]
    for name, m in models.items():
        a = m["accuracy"]
        mono = "--" if m["monotone_violation_rate"] is None else \
            f"{100 * m['monotone_violation_rate']:.1f}\\%"
        lines.append(
            f"{_tex(m['label'])} & {_f(a['brier'])} & {_f(a['log_loss'])} & "
            f"{_f(a['auc'], 3)} & {_f(a['ece'])} & {_f(m['seed_grid_sd'])} & "
            f"{_f(m['bootstrap_grid_sd'])} & "
            f"{mono} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{center}", ""]

    best = dec["best_challenger"]
    t = dec["tests"]
    vs = models[best]["vs_champion"]
    sig = (f"Wilcoxon $p = {vs['p_value']:.3f}$" if vs["p_value"] is not None
           else "per-gauge storm-bootstrap intervals")
    lines += [
        f"\\noindent\\textbf{{Decision:}} best challenger by pooled Brier is "
        f"{_tex(models[best]['label'])} (GBM Brier {_f(dec['brier_champion'])} vs "
        f"{_f(dec['brier_best_challenger'])}, gap {_f(dec['brier_gap_pct'], 2)}\\%; "
        f"{sig}).  Accuracy test {'passed' if t['accuracy'] else 'failed'}, "
        f"stability test {'passed' if t['stability'] else 'failed'}, "
        f"shape test {'passed' if t['shape'] else 'failed'}: "
        f"{_OUTCOME_TEXT[dec['outcome']]}.",
        "",
    ]

    if scored:
        lines += [
            "\\begin{center}\\small",
            "\\begin{longtable}{lrrccc}",
            "\\toprule",
            "\\textbf{Gauge} & \\textbf{Storms} & \\textbf{Flood rate} & "
            "\\textbf{GBM Brier} & \\textbf{Best chall.} & "
            "\\textbf{$\\Delta$ (95\\% CI)} \\\\",
            "\\midrule\\endhead",
        ]
        for g in scored:
            ci = g["vs_champion"][best]
            lines.append(
                f"{_tex(g['gauge_id'])} & {g['n_storms']} & {100 * g['flood_rate']:.1f}\\% & "
                f"{_f(g['accuracy'][CHALLENGER_CHAMPION]['brier'])} & "
                f"{_f(g['accuracy'][best]['brier'])} & "
                f"{ci['mean']:+.4f} [{ci['ci_low']:+.4f}, {ci['ci_high']:+.4f}] \\\\")
        lines += ["\\bottomrule", "\\end{longtable}", "\\end{center}",
                  "\\noindent $\\Delta$ is GBM minus challenger per-storm Brier; "
                  "positive favours the challenger."]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
