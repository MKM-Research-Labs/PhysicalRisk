"""Which dataset a run is executing against.

Some checks are only meaningful against a portfolio generated by an *earlier,
separate* pipeline run. The clearest case is the lineage hash comparison: it
asks whether the files on disk still match the manifest, which detects drift
between a recorded run and the current tree. When the portfolio is generated
immediately before the suite — the throwaway-fixture flow — the manifest is
written by the very run being checked, so the comparison always agrees and
verifies nothing.

Marking those full-dataset-only keeps them honest. The skip is deliberately
**off by default**: an ordinary run against the real portfolio executes them as
before, and only a run that has declared itself ephemeral skips, with the
reason stated. A skip that fired silently would be the failure mode this is
meant to remove, not a fix for it.

Set ``MKM_EPHEMERAL_DATASET=1`` in the generate → test → teardown wrapper.
"""

import os

import pytest

ENV_FLAG = "MKM_EPHEMERAL_DATASET"

_SKIP_REASON = (
    "full-dataset only: the portfolio was generated by this run, so a "
    "recorded-vs-current comparison is tautological. Run against the real "
    f"portfolio (without {ENV_FLAG}) to exercise it."
)


def ephemeral_dataset() -> bool:
    """True when the portfolio was generated by this run and will be deleted."""
    return os.environ.get(ENV_FLAG, "").strip().lower() in {"1", "true", "yes"}


#: Decorator for checks that only mean something against a pre-existing
#: portfolio. The condition is read at import, which is correct here: the
#: wrapper exports the flag before pytest starts. Anything that toggled it
#: mid-session would not be seen, so tests assert on ``ephemeral_dataset()``
#: rather than on this mark.
full_dataset_only = pytest.mark.skipif(
    ephemeral_dataset(), reason=_SKIP_REASON
)
